#!/usr/bin/env node
/**
 * Разбор спроса на подрядчиков: кого ищут, какими словами и с каким намерением.
 *
 *   node scripts/wordstat-specialists.mjs [core-spec] [core-msk] …
 *
 * Ключевая метрика — не общий объём, а КОММЕРЧЕСКАЯ доля. У свадебных ниш
 * половина спроса это «посмотреть картинки» (букеты, торты, арки): такие фразы
 * дают трафик, но не заявку. Считаем отдельно.
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = path.join(ROOT, 'scripts', 'wordstat-out');
const sources = process.argv.slice(2).filter((a) => !a.startsWith('--'));
const names = sources.length ? sources : ['core-spec'];

// Категории подрядчиков = будущие разделы каталога специалистов.
// Порядок важен: фраза уходит в первую подошедшую.
const CATS = [
  ['Ведущий', /ведущ|тамад|конферансье|распорядител/],
  ['Фотограф', /фотограф|фотосъем|фотосесс|фотоотчет|love story|лав стори/],
  ['Видеограф', /видеограф|видеосъ|видеосьем|свадебн\w* (видео|клип)|клип на свадьб/],
  ['Организатор и агентство', /организатор|агентств|координатор|организац|под ключ/],
  ['Выездная регистрация', /регистрац|регистратор|церемони/],
  ['Декор и оформление', /декор|оформлен|фотозон|арка|президиум|текстил|оформит|шары|свеч/],
  // «цвет» без уточнения ловит цветовую гамму свадьбы — берём только флористику.
  ['Флористика', /флорист|букет|цветы на свадьб|цветы для свадьб|цветочн|бутоньерк|оформление цветами/],
  ['Торт и десерты', /торт|кондитер|кенди|десерт|карава|капкейк|пирожн/],
  ['Кейтеринг и бар', /кейтеринг|фуршет|бармен|\bбар\b|алкогол|напитк|меню|повар|банкетное меню/],
  ['Музыка', /кавер|музыкант|музык|диджей|\bdj\b|саксофон|скрипач|вокалист|группа на свадьб/],
  ['Шоу и артисты', /шоу|артист|салют|фейерверк|пиротехн|фаер|файер|фокусник|танцор|номер на свадьб/],
  ['Стиль и красота', /стилист|визажист|макияж|прическ|образ невест|мастер по/],
  ['Транспорт', /лимузин|машин|автомобил|автобус|трансфер|транспорт|ретро авто|кортеж/],
  // «сцен» ловило сценарии, голый «звук» — саундтреки: только техника напрокат.
  ['Техника и прокат', /свет и звук|аренда звука|аренда мебел|аренда посуд|аренда шатр|\bшат[её]р|фотобуд|проектор|прокат (мебел|посуд|шатр|техник|свет|звук)/],
  ['Танец и подготовка пары', /постановка танца|первый танец|хореограф|репетиц/],
];

// Модификаторы намерения. Одна фраза может попасть в несколько.
const INTENT = {
  price: { title: 'цена', re: /сколько стоит|стоимость|\bцен|прайс|недорог|дешев|бюджет|за час|тариф/ },
  order: { title: 'заказ', re: /заказ|нанять|найти|услуг|аренд|снять|вызов|заказать|бронир/ },
  choice: { title: 'выбор', re: /как выбрать|отзыв|портфолио|рейтинг|лучш|топ |сравн|какой |какого /},
  geo: { title: 'гео', re: /москв|подмосков|московск/ },
  // «Посмотреть, как бывает»: картинки, идеи, примеры — трафик без заявки.
  // «фото» только отдельным словом, иначе под насмотренность уходит весь фотограф.
  look: {
    title: 'насмотренность',
    re: /\bфото\b|фотки|картинк|иде[ия]|пример|тренд|дизайн|красив|своими руками|мастер-класс|как сделать|схем|шаблон|\bвидео\b/,
  },
};

const TRASH = [
  /симс|sims|игр[аеы]?\b|четыре свадьбы|сериал|фильм|смотреть онлайн/,
  /\d+\s*(лет|год|года)|годовщин|кака[яй] свадьб/,
  /поздрав|тост|стих|открытк|пожелан|своими словами|с днем свадьбы/,
  /сонник|к чему снится|гороскоп|примет/,
  /порн|секс|скачать|торрент|вакансии|зарплата|обучение|курсы|как стать/,
  // Соседние ниши и омонимы: платья, телеигра «Что? Где? Когда?», прокат чего угодно.
  /плать|фата|что где когда|велосипед|вднх|коляск|детск/,
];

const merged = new Map();
for (const src of names) {
  const part = JSON.parse(await readFile(path.join(OUT_DIR, `${src}.json`), 'utf8'));
  for (const p of part.phrases) {
    const prev = merged.get(p.phrase);
    if (prev) prev.count = Math.max(prev.count, p.count);
    else merged.set(p.phrase, { phrase: p.phrase, count: p.count });
  }
}

// Ассоциации Вордстата тянут вообще всё, что рядом искали: платные дороги,
// зубные протезы, подписки. Требуем, чтобы фраза была про свадьбу или про
// подрядчика на празднике — иначе она не наша, как бы коммерчески ни звучала.
// Только свадебный интент. «Праздник», «торжество» и «банкет» тут стояли
// и затащили 36% чужого объёма: календарные «какой праздник» и «праздники
// России», а в организаторов — «услуги по организации праздников» (9 444).
// Смежные поводы — отдельный сбор, мешать их со свадьбой нельзя.
const RELEVANT = /свад|невест|жених|молодожен|венчан|бракосочет|wedding|выездн[ао][йя] регистрац/;

const rows = [...merged.values()].filter(
  (p) =>
    p.phrase.split(/\s+/).length > 1 &&
    RELEVANT.test(p.phrase) &&
    !TRASH.some((re) => re.test(p.phrase))
);

const buckets = new Map(CATS.map(([title]) => [title, []]));
for (const p of rows) {
  const hit = CATS.find(([, re]) => re.test(p.phrase));
  if (hit) buckets.get(hit[0]).push(p);
}

const sum = (list) => list.reduce((s, p) => s + p.count, 0);

const report = [];
for (const [title, list] of buckets) {
  if (!list.length) continue;
  const total = sum(list);
  const intents = {};
  for (const [key, { re }] of Object.entries(INTENT)) {
    const hits = list.filter((p) => re.test(p.phrase));
    intents[key] = { sum: sum(hits), n: hits.length, top: hits.sort((a, b) => b.count - a.count)[0] };
  }
  // Считать «всё кроме картинок» бесполезно: у запроса «букет невесты» слова
  // «фото» нет, а интент ровно такой. Берём обратное — фразы с ЯВНЫМ
  // намерением нанять: цена, заказ, выбор подрядчика.
  const hire = /сколько стоит|стоимость|\bцен|прайс|недорог|дешев|заказ|нанять|найти|услуг|аренд|снять|бронир|отзыв|портфолио|рейтинг|как выбрать|лучш/;
  const commercial = sum(list.filter((p) => hire.test(p.phrase)));
  report.push({
    title,
    total,
    n: list.length,
    commercial,
    share: Math.round((commercial / total) * 100),
    intents,
    top: list.sort((a, b) => b.count - a.count).slice(0, 6),
  });
}

report.sort((a, b) => b.commercial - a.commercial);

// ---------- консоль ----------
console.log('\nКатегория                   всего   с намер.  доля   фраз');
for (const r of report) {
  console.log(
    `${r.title.padEnd(26)} ${String(r.total).padStart(7)} ${String(r.commercial).padStart(9)}  ${String(r.share).padStart(3)}%  ${String(r.n).padStart(5)}`
  );
}

// ---------- отчёт ----------
const lines = [
  '# Спрос на специалистов (Москва + МО)',
  '',
  `Источник: ${names.join(', ')}. Фраз после чистки: ${rows.length}.`,
  'Частоты — показы в месяц, широкое соответствие.',
  '',
  '«С намерением нанять» — фразы с явным модификатором: цена, заказ, услуги,',
  'отзывы, выбор. Остальное — насмотренность: трафик в блог, но не заявка.',
  '',
  '| Категория | Всего | С намерением нанять | Доля | Фраз |',
  '| --- | ---: | ---: | ---: | ---: |',
  ...report.map(
    (r) => `| ${r.title} | ${r.total.toLocaleString('ru')} | ${r.commercial.toLocaleString('ru')} | ${r.share}% | ${r.n} |`
  ),
  '',
];

for (const r of report) {
  lines.push(
    `## ${r.title}`,
    '',
    `Всего ${r.total.toLocaleString('ru')} показов, из них с намерением нанять ${r.commercial.toLocaleString('ru')} (${r.share}%).`,
    '',
    '| Частота | Запрос |',
    '| ---: | --- |',
    ...r.top.map((p) => `| ${p.count.toLocaleString('ru')} | ${p.phrase} |`),
    '',
    'Намерения: ' +
      Object.entries(INTENT)
        .map(([key, { title }]) => `${title} — ${r.intents[key].sum.toLocaleString('ru')}`)
        .join(' · '),
    ''
  );
}

await writeFile(path.join(OUT_DIR, 'specialists.md'), lines.join('\n'), 'utf8');
console.log('\n→ scripts/wordstat-out/specialists.md');
