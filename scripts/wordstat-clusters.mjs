#!/usr/bin/env node
/**
 * Разбор сырого ядра из wordstat.mjs batch: чистка мусора и раскладка
 * по осям, которыми живёт каталог (тип × вместимость × гео × цена),
 * плюс отдельные корзины подрядчиков и информационных запросов.
 *
 *   node scripts/wordstat-clusters.mjs [core-msk]
 *
 * На выходе: scripts/wordstat-out/<имя>-clean.csv и <имя>-clusters.md
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = path.join(ROOT, 'scripts', 'wordstat-out');

// Ассоциации Вордстата тянут в ядро всё, что рядом искали: игру Sims,
// телешоу, поздравления, подарки. Для агрегатора площадок это балласт.
const TRASH = [
  /симс|sims|майнкрафт|роблокс|игр[аеы]?\b/,
  /четыре свадьбы|давай поженимся|сериал|фильм|смотреть|серия|актер|песн|клип|танец живота/,
  /годовщин|поздрав|тост|конкурс|прикол|стих|проза|открытк|смс|пожелан/,
  /подар|что дарить|приданн|выкуп невесты|кража невесты/,
  /сонник|к чему снится|гороскоп|примет|нумеролог|заговор|молитв/,
  /купить квартиру|регистратура|смет[аеы]|вакансии|работа|отзывы сотрудник/,
  /порн|секс|голы|эротик/,
  /развод|расторжение|алимент|брачный договор|фиктивн/,
  // Товарный пласт (платья, салоны, образы) — соседняя ниша, не наша.
  /плать|фата|костюм|туфли|кольц|украшени|маникюр|прическ|макияж|наряд|салон|образ невест|аксессуар/,
  /с днем свадьбы|своими словами|с бракосочетанием|горько|приданым|светлячк|безумн|пиратск|угар|невозможн|во сне|наша свадьба|дом невесты|жених приехал/,
  /бесплатно|скачать|шаблон|торрент|онлайн смотреть/,
  /вики|википеди|значение слова|что такое свадьба|свадьба это/,
  // Годовщины: «15 лет какая свадьба» — самый жирный паразитный пласт в ассоциациях.
  /\d+\s*(лет|год|года)/,
  /кака[яй] свадьб|свадьбы по годам|золотая свадьба|серебряная свадьба|ситцев|деревянн|розовая свадьба|красная свадьба/,
  // Регистрация в ЗАГСе — не наш предмет (мы про выездную и про банкет).
  /дворец бракосочетан|\bзагс\b|подать заявлен|госуслуг/,
  // Песни, шоу, кино, путешествия.
  /марш|танец|в слепую|лучшего друга|свадьбы не будет|ах эта|путешестви|медовый месяц|цыганск|кровав/,
  /после свадьбы|вторая свадьба|повторная свадьба|^2 свадьба/,
];

// Фраза попадает в ядро, только если она про наш предмет.
const RELEVANT = /свад|жених|невест|бракосочет|молодожен|wedding|банкетн|выездн[ао][йя] регистрац/;

// Порядок важен: фраза уходит в первый подошедший кластер.
// Сначала — то, что определяет раздел сайта (подрядчик vs площадка),
// потом оси подборки, и только в конце гео: город есть почти в каждой
// коммерческой фразе и иначе стянул бы на себя всё ядро.
const CLUSTERS = [
  {
    key: 'vendors',
    title: 'Подрядчики — раздел «Специалисты»',
    re: /ведущ|тамад|фотограф|фотосесс|видеограф|фотозон|декор|оформлен|флорист|букет|торт|кондитер|стилист|визажист|диджей|\bdj\b|кавер|музык|артист|салют|фейерверк|организатор|агентств|координатор|регистрац|шоу|фокусник/,
  },
  {
    key: 'venue-type',
    title: 'Тип площадки — оси подборок',
    re: /лофт|банкетн|ресторан|кафе|усадьб|особняк|шат[её]р|коттедж|загородн|веранд|яхт|теплоход|катер|крыш|оранжере|шале|база отдыха|отел|гостиниц|глэмпинг|дом[а]? для свадьб|поместь|замок|терем|парк-отель|на природе|у воды|в лесу|в саду/,
  },
  {
    key: 'capacity',
    title: 'Вместимость — оси подборок',
    re: /на \d+ (человек|гост|персон)|\d+ гостей|камерн|маленьк|небольш|для двоих|вдво[её]м|без гостей|мини-свадьб/,
  },
  {
    key: 'price',
    title: 'Цена и условия — коммерческий интент',
    // \b перед «цен», иначе в кластер уезжает «с-ЦЕНА-рий свадьбы».
    re: /недорог|дешев|бюджетн|\bцен|стоимость|сколько стоит|стоила|прайс|аренд|снять|под ключ|скидк|пробков|со своим алкогол|депозит|минимальн|за столик/,
  },
  {
    key: 'geo',
    title: 'География — оси подборок',
    re: /москв|подмосков|московск|истр|клязьм|новая риг|рубл[её]в|дмитров|одинцов|красногорск|мытищ|химк|пушкин|солнечногорск|сергиев|звенигород|цао|зао|сао|ювао|свао|юзао|зелен|мкад|области?\b/,
  },
  {
    key: 'info',
    title: 'Информационные запросы — темы блога',
    re: /как |что |где |когда |почему|зачем|чек-?лист|список|план |тайминг|сценар|иде[ия]|стил|рассадк|приглашен|пригласительн|месяц|сезон|подготовк|этап|ошибк|совет|правил|традиц|обыча|тренд|сентябр|октябр|ноябр|декабр|январ|феврал|март|апрел|\bма[йея]\b|июн|июл|август|зим|осен|весн|летн/,
  },
  {
    key: 'core',
    title: 'Общий спрос на площадку',
    re: /площадк|место для свадьб|зал|провести|отметить|банкет|организац|проведени/,
  },
];

// Выгрузок может быть несколько (проходы сбора) — склеиваем в одно ядро,
// у повторов оставляем большую частоту.
const sources = process.argv.slice(2).filter((a) => !a.startsWith('--'));
const names = sources.length ? sources : ['core-msk'];
const outName = names.length > 1 ? 'core-all' : names[0];

const merged = new Map();
let collectedAt = '';
let regions = null;
const seedTotals = [];

for (const src of names) {
  const part = JSON.parse(await readFile(path.join(OUT_DIR, `${src}.json`), 'utf8'));
  collectedAt = part.collectedAt > collectedAt ? part.collectedAt : collectedAt;
  regions = regions ?? part.regions;
  seedTotals.push(...(part.seeds ?? []));
  for (const p of part.phrases) {
    const prev = merged.get(p.phrase);
    if (prev) {
      prev.count = Math.max(prev.count, p.count);
      prev.kinds = [...new Set([...prev.kinds, ...p.kinds])];
    } else {
      merged.set(p.phrase, { ...p });
    }
  }
}

const raw = { collectedAt, regions, seeds: seedTotals, phrases: [...merged.values()] };

const clean = raw.phrases.filter(
  (p) =>
    // Однословные обрывки («свадебный», «wedding») частотны, но интента не несут.
    p.phrase.trim().split(/\s+/).length > 1 &&
    RELEVANT.test(p.phrase) &&
    !TRASH.some((re) => re.test(p.phrase))
);

const buckets = new Map(CLUSTERS.map((c) => [c.key, []]));
buckets.set('rest', []);
for (const p of clean) {
  const hit = CLUSTERS.find((c) => c.re.test(p.phrase));
  buckets.get(hit ? hit.key : 'rest').push(p);
}

const sum = (rows) => rows.reduce((a, r) => a + r.count, 0);
const csvCell = (s) => (/[;"\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s);

// --- CSV чистого ядра с проставленным кластером ---
const clusterOf = (p) => (CLUSTERS.find((c) => c.re.test(p.phrase)) ?? { key: 'rest' }).key;
const csv = [
  'phrase;count;cluster;kind',
  ...clean
    .slice()
    .sort((a, b) => b.count - a.count)
    .map((p) => `${csvCell(p.phrase)};${p.count};${clusterOf(p)};${p.kinds.join('+')}`),
].join('\n');
await writeFile(path.join(OUT_DIR, `${outName}-clean.csv`), '﻿' + csv, 'utf8');

// --- отчёт ---
const lines = [
  `# Семантическое ядро: ${outName}`,
  '',
  `Снято ${raw.collectedAt.slice(0, 10)}, регионы ${(raw.regions ?? ['все']).join(', ')} (213 — Москва, 1 — МО).`,
  `Сырых фраз ${raw.phrases.length}, после чистки ${clean.length}. Частота — показы в месяц, широкое соответствие.`,
  '',
];

for (const c of [...CLUSTERS, { key: 'rest', title: 'Прочее (проверить руками)' }]) {
  const rows = buckets.get(c.key).sort((a, b) => b.count - a.count);
  if (!rows.length) continue;
  lines.push(
    `## ${c.title}`,
    '',
    `${rows.length} фраз, суммарно ${sum(rows).toLocaleString('ru')} показов/мес.`,
    '',
    '| Частота | Запрос |',
    '| ---: | --- |',
    ...rows.slice(0, 40).map((r) => `| ${r.count.toLocaleString('ru')} | ${r.phrase} |`),
    ''
  );
}

await writeFile(path.join(OUT_DIR, `${outName}-clusters.md`), lines.join('\n'), 'utf8');

console.log(`Чистое ядро: ${clean.length} фраз из ${raw.phrases.length}`);
for (const c of [...CLUSTERS, { key: 'rest', title: 'Прочее' }]) {
  const rows = buckets.get(c.key);
  console.log(`  ${c.title.padEnd(42)} ${String(rows.length).padStart(5)} фраз  ${sum(rows).toLocaleString('ru').padStart(10)} показов`);
}
console.log(`\n→ ${outName}-clean.csv, ${outName}-clusters.md`);
