// ============ БЛОКИ ТЕЛА ============
// Тело статьи — данные, а не HTML: так контент переносится в базу
// без переписывания шаблона, а вёрстка остаётся семантической.
export type ArticleBlock =
  | { kind: 'h2'; text: string }
  | { kind: 'p'; text: string }
  | { kind: 'list'; items: string[] }
  | { kind: 'image'; src: string; alt: string }
  /** Таблица сравнения: первая колонка — заголовок строки (площадка, параметр) */
  | { kind: 'table'; caption?: string; head: string[]; rows: string[][] }
  /** Вопросы из ядра с короткими ответами; на странице уходят и в JSON-LD FAQPage */
  | { kind: 'faq'; items: { q: string; a: string }[] };

/** Ссылка на подборку каталога: анкор — то, чем её называют в тексте */
export interface Collection {
  label: string;
  href: string;
}

export interface Article {
  slug: string;
  rubricSlug: string;
  title: string;
  lead: string;
  cover: { src: string; alt: string };
  /** ISO-даты: публикация и переобновление (конкурент переобновляет тексты — работает) */
  published: string;
  updated?: string;
  body: ArticleBlock[];
  collections: Collection[];
  /** имена площадок из ленты каталога (data/feed.ts) */
  venues: string[];
  seo: { title: string; description: string };
}

