// ============ ИНЛАЙН-РАЗМЕТКА ============
// В тексте разрешены ровно две вещи: ссылка [анкор](/url) — контекстная
// перелинковка на подборки, и ==фраза== — фирменный маркер (правило проекта:
// жирность внутри абзаца запрещена). Ничего больше в наборный текст не попадает.
const escapeHtml = (s: string) =>
  s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!);

// Типограф: висячие предлоги и союзы (1–2 буквы) клеятся к следующему
// слову, число — к своей единице и к разряду тысяч. Только неразрывный
// пробел, никакой другой замены текста.
const NBSP = ' ';
export function typograf(text: string): string {
  return text
    .replace(/(^|[\s(«])([а-яА-ЯёЁa-zA-Z]{1,2})\s+(?=\S)/g, `$1$2${NBSP}`)
    .replace(/(\d)\s(?=\d{3}(?!\d))/g, `$1${NBSP}`)
    .replace(/(\d)\s(?=(?:₽|%|м²|га|км|гост|человек|тыс|стул))/g, `$1${NBSP}`)
    .replace(/\s(?=[—–])/g, NBSP);
}

export function inlineHtml(text: string): string {
  return escapeHtml(typograf(text))
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2">$1</a>')
    .replace(/==([^=]+)==/g, '<mark>$1</mark>');
}
