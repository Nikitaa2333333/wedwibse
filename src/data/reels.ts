// Доска на главной — единый поток фотографий и видео: ролик лежит в нём
// такой же плиткой, как снимок, без ярлыка «видео» и без отдельной секции.
// Поэтому ролики, не принадлежащие конкретной площадке, живут здесь, а не
// в gallery карточки: подмешать чужой кадр к площадке — соврать в выдаче.
//
// Плитка отсюда никуда не ведёт: ссылки нет, потому что нет карточки, на
// которую она указывала бы. Появится источник (видеограф со своей страницей,
// подборка) — добавляем href, доска обернёт кадр в ссылку сама.
//
// Файлы: ролик в public/reels/, постер тем же именем в src/assets/reels/
// (правила подготовки — VIDEO.md). Демо-контент: реальные ролики приедут
// от подрядчиков вместе с их карточками.
// ============================================================

