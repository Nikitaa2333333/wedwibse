// дописывает. В данных карточки структура не хранится — только разделы
// (StorySection), которые из неё получились.
//
// Категория без своей структуры получает `DEFAULT_STRUCTURE`.

export interface SuggestedSection {
  /** заголовок раздела — первая строка блока текста */
  title: string;
  /** подсказка серым внутри пустого блока: о чём написать */
  hint: string;
}

export interface SuggestedStructure {
  /** подпись: «Структура фотографа» */
  label: string;
  sections: SuggestedSection[];
}

