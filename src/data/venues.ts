/** Крупная сцена для скролл-блока «фото справа / текст слева» */
export interface VenueScene {
  /** порядковый номер, показывается как 01, 02… */
  num: string;
  title: string;
  /** абзацы; первый — главный, дальше подробности */
  body: string[];
  /** короткие факты сцены (без маркеров — это метка/значение) */
  facts?: { label: string; value: string }[];
  image: string;
  alt: string;
  /**
   * Как сцена ложится на страницу. Нужна, чтобы полотно не было
   * однотипным: подряд идущие «текст слева / кадр справа» утомляют.
   *  split   — по умолчанию: текст слева, липкий кадр справа;
   *  wide    — широкий кадр во всю ширину, текст под ним;
   *  gallery — лента кадров со свайпом, текст под ней.
   */
  layout?: 'split' | 'wide' | 'gallery';
  /** кадры для layout: 'gallery' — первым идёт image, если список пуст */
  images?: string[];
}

export interface VenueRow {
  label: string;
  value: string;
}

export interface Venue {
  slug: string;
  /** города каталога: /moskva/ploshchadki/... */
  citySlug: string;
  city: string;
  category: string;
  categorySlug: string;

  name: string;
  kicker: string;
  /** h1 страницы */
  title: string;
  lead: string;

  /** Собственный знак площадки. Файл — белый на прозрачном, лежит в public/
   *  (нужен стабильный сырой URL: цвет даёт CSS-маска, а не сам файл, —
   *  так знак сам подхватывает цвет секции и живёт и на креме, и на тёмном).
   *  ratio — пропорции файла для aspect-ratio, чтобы знак не плющило. */
  logo?: { src: string; ratio: string; label: string };

  hero: { image: string; alt: string; portrait: string; portraitAlt: string };

  /** строки характеристик под первым экраном */
  meta: VenueRow[];

  /** крупные цифры-факты полосой */
  stats: { value: string; label: string }[];

  scenes: VenueScene[];

  /** блоки «условия» — каждый со своим заголовком */
  terms: { title: string; rows: VenueRow[] }[];

  /** Заголовок секции условий. По умолчанию «Сколько стоит и как забронировать»;
   *  площадкам без открытого прайса ставим свой, чтобы не обещать цифры,
   *  которых на странице нет. */
  termsTitle?: string;

  /**
   * Документы площадки: техническое сопровождение, спецификация оборудования,
   * презентация. Файл лежит в public/docs/ — ему нужен стабильный сырой URL
   * (astro:assets жмёт картинки, PDF через него не проходит).
   */
  docs?: { title: string; note: string; file: string; size: string }[];

  included: { title: string; note?: string; items: string[] }[];
  extras: { title: string; note?: string; rows: VenueRow[] }[];

  rules: { title: string; text: string }[];

  gallery: { src: string; alt: string; wide?: boolean }[];

  faq: { q: string; a: string[] }[];

  contacts: {
    address: string;
    addressNote: string;
    /** Точка на карте. Геокодируем один раз при заведении карточки и храним
     *  цифрами: клиентский геокодер требует отдельного ключа и лишнего запроса
     *  на каждую загрузку. Без geo площадка просто не попадает на карту. */
    geo?: { lat: number; lon: number };
    phone: string;
    phoneHref: string;
    email: string;
    hours: string;
    routes: VenueRow[];
    links: { label: string; href: string }[];
  };

  seo: { title: string; description: string; ogImage: string };
}

