// ============ ОТЗЫВЫ О ПЛОЩАДКАХ ============
// Источник — публичная карточка площадки в Яндекс.Картах. Тянет скрипт
// scripts/maps-reviews.mjs из HTML, который отдаёт Firecrawl (страница
// /reviews/ с прокруткой), без участия модели. Храним ТОЛЬКО свежие:
// 20 последних по дате, остальное на витрине не нужно. Агрегат (оценка,
// число оценок, число отзывов) — целиком с Карт, не считается из
// показанных.
//
// Один файл на площадку: src/data/reviews/<slug>.json. Это та же форма,
// что запись коллекции venue_reviews в PocketBase (pb/pb_migrations):
// когда база станет боевой, файлы уедут туда через pb-seed, а страница
// продолжит получать готовый агрегат и список.
//
// Тексты не редактированы — это настоящие отзывы настоящих людей.
// НО ПОКАЗЫВАЕМ НЕ ВСЁ СОБРАННОЕ: витрину задаёт showcaseReviews() ниже.
// Раньше на странице стояли все 20 свежих, включая единицы и двойки;
// решение заказчика 14.09.2026 — последние 10 с оценкой 4 и выше.
// Смысл границы именно в ЧЕТВЁРКАХ, а не в пятёрках: страница из одних
// пятёрок читается как накрутка, а четвёрка в ленте отзывов возвращает
// ей достоверность, не превращая карточку партнёра в разбор жалоб.
// Сырьё в файлах остаётся полным — режется только показ.
//
// ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ: источник в интерфейсе не назван и ссылки на
// него нет — так решено продуктово. Из этого следует долг, который надо
// закрыть ДО открытия сайта поисковикам: показывать чужие пользовательские
// тексты у себя без согласования — риск и по правам авторов, и по
// правилам сервиса-источника. Варианты: договориться с площадкой и собирать
// отзывы самим, брать их из своей брони, либо назвать источник явно.

export interface VenueReview {
  author: string;
  /** человеку, а не машине: «26 мая 2026» */
  date: string;
  /** ISO-дата для сортировки и записи в базу */
  iso?: string | null;
  /** 1–5, целое: половинок в отзывах не бывает */
  rating: number;
  text: string;
}

export interface VenueReviewsBlock {
  /** откуда взято: yandex-maps | site | own */
  source?: string;
  /** когда тянули, YYYY-MM-DD */
  pulled?: string;
  /** средняя оценка, как её показывает источник */
  rating: number;
  /** сколько всего людей поставило оценку (оценка без текста тоже считается) */
  ratings: number;
  /** сколько отзывов С ТЕКСТОМ — это число и стоит рядом с оценкой */
  total: number;
  /** показанные на странице, свежие сверху; порядок задан в файле, не в вёрстке */
  items: VenueReview[];
}

const files = import.meta.glob<VenueReviewsBlock>('./reviews/*.json', {
  eager: true,
  import: 'default',
});

export const VENUE_REVIEWS: Record<string, VenueReviewsBlock> = Object.fromEntries(
  Object.entries(files).map(([path, block]) => [path.replace(/^.*\/([^/]+)\.json$/, '$1'), block])
);

/** Отзывы площадки по слагу — нет записи, значит блок на странице не рисуется. */
export function venueReviews(slug: string): VenueReviewsBlock | null {
  return VENUE_REVIEWS[slug] ?? null;
}

/** минимальная оценка отзыва, который попадает на витрину */
export const SHOWCASE_MIN_RATING = 4;
/** сколько отзывов показываем на карточке */
export const SHOWCASE_LIMIT = 10;

/**
 * ВИТРИНА ОТЗЫВОВ — что из собранного видно на странице партнёра.
 * Последние SHOWCASE_LIMIT отзывов с оценкой от SHOWCASE_MIN_RATING.
 *
 * Порядок берём как он есть в источнике (свежие сверху — так их кладёт
 * scripts/maps-reviews.mjs, так же собран reviewsList у подрядчика), и
 * не пересортировываем: у отзывов подрядчика ISO-даты нет вовсе, только
 * человеческая строка, и сортировка по ней дала бы алфавит, а не даты.
 *
 * Общий агрегат (оценка, число оценок, число отзывов) НЕ пересчитываем
 * из показанных — он остаётся с источника: показываем десять, а стоит за
 * оценкой по-прежнему несколько сотен человек.
 *
 * Дженерик, а не VenueReview: тем же правилом живёт и карточка подрядчика
 * (reviewsList в data/specialists) — второй копии правила не заводим.
 */
export function showcaseReviews<T extends { rating: number }>(items: T[]): T[] {
  return items.filter((r) => r.rating >= SHOWCASE_MIN_RATING).slice(0, SHOWCASE_LIMIT);
}
