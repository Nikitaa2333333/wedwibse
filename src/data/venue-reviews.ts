// ВРЕМЕННЫЕ ДАННЫЕ (дизайн-фаза). Собраны с публичной карточки площадки
// в картографическом сервисе: агрегат (оценка, сколько всего оценок,
// сколько отзывов) и первые отзывы с текстом. Тексты не редактированы —
// это настоящие отзывы настоящих людей, включая неидеальные: четвёрка
// и тройка в списке стоят намеренно, витрина из одних пятёрок читается
// как накрутка и не помогает выбрать.
//
// ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ: источник в интерфейсе не назван и ссылки на
// него нет — так решено продуктово. Из этого следует долг, который надо
// закрыть ДО открытия сайта поисковикам: показывать чужие пользовательские
// тексты у себя без согласования — риск и по правам авторов, и по
// правилам сервиса-источника. Варианты на выбор: договориться с
// площадкой и собирать отзывы самим, взять их из своей брони, либо
// назвать источник явно. Сейчас это демонстрация вёрстки, а не витрина.
//
// Когда появится бэкенд, форма записи не меняется: страница получает
// готовый агрегат и список — неважно, лежит он в файле или приходит
// из базы.

export interface VenueReview {
  author: string;
  /** человеку, а не машине: «26 мая 2026» */
  date: string;
  /** 1–5, целое: половинок в отзывах не бывает */
  rating: number;
  text: string;
}

export interface VenueReviewsBlock {
  /** средняя оценка, как её показывает источник */
  rating: number;
  /** сколько всего людей поставило оценку (оценка без текста тоже считается) */
  ratings: number;
  /** сколько отзывов С ТЕКСТОМ — это число и стоит рядом с оценкой */
  total: number;
  /** показанные на странице, свежие сверху; порядок задан здесь, не в вёрстке */
  items: VenueReview[];
}

