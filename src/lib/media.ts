// ============================================================
// ВИДЕО В КАДРАХ КАРТОЧКИ.
// media у карточки — массив кадров; видео просто один из его элементов
// ('/venues/river-loft/gal/clip.mp4'). Отличаем по расширению, никакого
// отдельного поля в данных не заводим: так новая категория подрядчиков
// получит видео без правки схемы.
//
// ГДЕ ЛЕЖАТ ФАЙЛЫ (важно, потому что правило другое, чем у фото):
//   ролик  — public/venues/.../clip.mp4      (Astro видео не пережимает,
//            astro:assets работает только с картинками — ролику нужен
//            стабильный сырой URL);
//   постер — src/assets/venues/.../clip.webp (тот же путь, расширение
//            .webp) — он обычное фото и проходит через <Image>: сжатие,
//            srcset, ленивая загрузка.
// Постер обязателен: без него сборка упадёт на resolveImage — и это
// правильно, кадр без постера в ленте показывать нельзя.
//
// ГОТОВИТЬ РОЛИК ЗАРАНЕЕ (см. VIDEO.md): 6–8 секунд, без звуковой дорожки
// вообще, H.264, потолок 720p, 1–2 МБ. Пережатие «на лету» не делает никто:
// ни Astro, ни nginx.
// ============================================================

import { resolveImage } from './images';

const VIDEO_EXT = /\.(mp4|webm)$/i;

export function isVideo(src: string): boolean {
  return VIDEO_EXT.test(src);
}

/** постер ролика: тот же путь с расширением .webp — лежит в src/assets */
export function posterOf(src: string): string {
  return src.replace(VIDEO_EXT, '.webp');
}

/** только фотографии — там, где нужен статичный кадр (обложка, дуо-карточка) */
export function photosOnly(media: string[]): string[] {
  return media.filter((src) => !isVideo(src));
}

/**
 * Идентификатор кадра для адреса страницы: имя файла без папок и расширения
 * (`/venues/river-loft/gal/g4.webp` → `g4`).
 *
 * По нему карточка площадки открывается НА ТОМ САМОМ кадре, по которому
 * человек нажал в доске: нажал на свечи — открылись свечи, а не дежурный
 * первый экран площадки. Ссылаемся именем файла, а не номером в галерее:
 * номер поедет при первой же перестановке кадров в venues.ts, имя — нет.
 *
 * Живёт здесь, а не в lib/gallery: gallery тянет за собой весь каталог
 * (VENUES, ARTICLES, REELS), а идентификатор кадра нужен и самому рельсу.
 */
export function frameId(src: string): string {
  return src.split('/').pop()!.replace(/\.[^.]+$/, '');
}

/** width/height кадра — у ролика берётся с постера, файл видео Astro не читает */
export function ratioOf(src: string): number {
  const meta = resolveImage(isVideo(src) ? posterOf(src) : src);
  return meta.width / meta.height;
}

/**
 * Порог «это ещё вертикальный/квадратный кадр, а не горизонтальный».
 * ЕДИНАЯ ГРАНИЦА НА ВЕСЬ ПРОЕКТ — раньше то же число (1.05) жило только
 * внутри lib/gallery.ts для доски, и первый экран площадки при выборе
 * дежурного кадра считал вертикальность на свой лад (< 1). Два разных
 * порога в двух местах — ровно то, что система должна была исключить:
 * с ростом каталога такие расхождения не отсматриваются, они просто
 * тихо накапливаются. Немного шире единицы: почти квадратный кадр
 * (соотношение чуть за 1) в вертикальной колонке/герое всё ещё смотрится
 * нормально, а вот настоящий горизонтальный — уже нет.
 */
export const PORTRAIT_MAX_RATIO = 1.05;

export function isPortrait(src: string): boolean {
  return ratioOf(src) <= PORTRAIT_MAX_RATIO;
}
