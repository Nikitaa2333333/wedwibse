// ============================================================
// КАРТОЧКА КАТАЛОГА СПЕЦИАЛИСТОВ — общий контракт между страницей
// категории и сеткой (components/SpecialistGrid.astro).
//
// Страница категории сама решает, что у неё за цена и по каким бакетам
// её раскладывать: у ведущих это «за 6 часов работы», у фотографов —
// «за час» и «минимальный бюджет». Сетка не должна знать про эти правила,
// поэтому получает уже готовые значения.
// ============================================================
import type { Specialist } from '../data/specialists';

export type CardVariant = '' | 'scard--wide' | 'scard--duo';

export interface SpecialistCard {
  s: Specialist;
  variant: CardVariant;
  /** подпись рядом с ценой: стиль ведения, стиль съёмки и т.п. */
  styleTag: string;
  /** значения фильтров этой карточки — их читает клиентский фильтр */
  filters: Record<string, string | string[]>;
  sortKey: { price: number; rating: number };
  /** цена строкой: «от 75 000 ₽» либо «Цена по запросу» */
  price: string;
  href: string;
  /** данные кнопки «в избранное» — готовит страница (нужен пережатый кадр) */
  save: string;
}

/** Каденция размеров мозаики — общая для всех категорий.
 *  wide — раз в 6 карточек, duo — тоже раз в 6, со сдвигом: на 12 карточках
 *  при 4 колонках это ровно 4 полных ряда, при 2 и 3 dense укладывает без дыр. */
export function variantOf(i: number): CardVariant {
  if (i % 6 === 1) return 'scard--wide';
  if (i % 6 === 4) return 'scard--duo';
  return '';
}
