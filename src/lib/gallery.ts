// СКОЛЬКО ЛЕНТА БЕРЁТ С ОДНОЙ КАРТОЧКИ
//
// Лента — витрина КАТАЛОГА, а не альбом одной карточки. Пока карточек
// одиннадцать, «взять у каждой всё, что есть» означает, что каждая
// одиннадцатая плитка — одна и та же площадка или один и тот же человек:
// на телефоне это примерно раз в полтора экрана, то есть постоянно.
//
// Отдельно про людей. У ведущего, вокалиста, диджея портфолио — ОН САМ:
// все кадры это один человек в разных залах. Двадцать таких кадров
// в ленте отличаются друг от друга куда меньше, чем двадцать кадров
// площадки, и читаются не как каталог, а как чей-то личный аккаунт.
// Поэтому у этих категорий потолок втрое ниже — и он про ЛИЦО, а не про
// качество карточки: у фотографа или декоратора в photos работы, там
// кадр от кадра отличается.
//
// Потолок в ПЛИТКАХ, а не в кадрах: плитка может нести три кадра, и
// считать надо то, сколько раз карточка попадается на глаза.
// С ростом каталога потолок перестанет срабатывать сам собой — при
// полусотне карточек до него никто не дотянется.
//
// РОЛИКИ ПОТОЛОК НЕ РЕЖЕТ, и это осознанно: двенадцать роликов площадки
// — это двенадцать РАЗНЫХ съёмок (интерьер, подача, облёт), они и в ленте
// читаются как разное. Потолок же придуман против повтора одного и того
// же — одного лица, одного зала с другой точки. Окажется, что и видео
// примелькалось, — потолок на ролики заводится здесь же, в reelPins.
// ============================================================
// Пул ленты теперь бесконечный (см. BOARD_TILE_LIMIT), и потолок на
// карточку — единственное, что не даёт одной площадке с полусотней кадров
// занять каждую четвёртую плитку: 12 плиток ≈ 18 кадров, по кругу с ~46
// карточками одна и та же площадка попадается раз в полтора-два экрана.
const PER_CARD_TILES = 12;
const PER_CARD_TILES_FACE = 3;

// ПОТОЛОК ГЛАВНОЙ ЦЕЛИКОМ. PER_CARD_TILES режет то, что даёт ОДНА карточка,
// но не сумму по всей доске: с ростом каталога (сейчас 11 площадок и ~35
// подрядчиков) сумма растёт линейно и дальше только больше при каждой
// новой карточке. Резать нужно уже ПЕРЕМЕШАННЫЙ поток (после interleave/
// spread и вставки статей), а не «первые N по порядку источников»: VENUES
// в массиве идут первыми, и такой срез оставил бы в первом экране одни
// площадки, целиком выкинув подрядчиков, ролики и статьи.
//
// Два числа, а не одно. BOARD_SHOWN — сколько плиток стоит в колонках
// сразу (3–4 экрана прокрутки: 2 колонки на телефоне, 4–5 на ПК); всё
// остальное до BOARD_TILE_LIMIT лежит в HTML скрытым хвостом и досыпается
// в колонки САМО при прокрутке — бесконечная лента, как в Pinterest
// (limit + infinite у PhotoMasonry). Скрытый кадр браузер не грузит,
// поэтому хвост стоит только байтов HTML: ~1,2 КБ на плитку до gzip,
// и BOARD_TILE_LIMIT — предохранитель именно на это. Сейчас потолок выше
// всего каталога (≈290 плиток при 11 площадках и ~35 подрядчиках), то есть
// лента идёт до последнего кадра; упрёмся в него с ростом каталога —
// следующий шаг не кнопка, а порции с сервера (когда появится бэкенд).
// Пока пул был равен видимой части (44), доска при ~46 карточках брала по
// ОДНОЙ плитке с карточки, и долитые в галереи кадры до главной не доезжали.
//
// ОТДЕЛЬНОГО «ХУКА» НА НОВЫЕ ФОТО НЕТ И НЕ НУЖНО: collectTiles читает
// VENUES / REAL_SPECIALISTS / REELS целиком на каждой сборке, и новый JSON
// или новые кадры в галерее попадают в ленту сами со следующим пушем
// в master (деплой — см. CLAUDE.md). Живое обновление без пересборки —
// это уже бэкенд, не эта фаза.
export const BOARD_SHOWN = 44;
const BOARD_TILE_LIMIT = 320;

/** Категории, где портфолио — сам подрядчик, а не его работы. */
const SELF_PORTFOLIO = new Set([
  'vedushchie',
  'vokalisty',
  'muzykanty',
  'dj',
  'kaver-gruppy',
  'horeografy',
  'animatory',
  'fokusniki',
]);

function capOf(s: Specialist): number {
  return SELF_PORTFOLIO.has(s.categorySlug) ? PER_CARD_TILES_FACE : PER_CARD_TILES;
}

/** ПОТОЛОК КАРТОЧКИ НЕ РЕЖЕТ ГОРИЗОНТАЛЬНЫЕ ПОДЧИСТУЮ. Горизонтальные в
 *  галереях лежат ближе к концу (экстерьер, общий план, у фотографов —
 *  репортаж), и простой slice(0, cap) терял именно их: на доске оставалось
 *  17 % низких плиток, колонки шли в ногу. Но и «взять все» нельзя — так
 *  доска получала 60 % низких, и рвать ритм стало нечему: полоска на
 *  полоске. Держим долю WIDE_SHARE от потолка карточки: столько низких
 *  плиток берём (в их порядке), остаток потолка — первые вертикальные.
 *  Порядок внутри карточки не меняем, разводит по потоку spreadWide. */
const WIDE_SHARE = 0.4;

function capKeepWide(pins: Pin[], cap: number): Pin[] {
  const wide = pins.filter((p) => isWide(p.height)).slice(0, Math.ceil(cap * WIDE_SHARE));
  const tall = pins.filter((p) => !isWide(p.height)).slice(0, cap - wide.length);
  const keep = new Set([...wide, ...tall]);
  return pins.filter((p) => keep.has(p));
}

/** ПЕРВЫЙ РЯД ДОСКИ — ВЕРТИКАЛЬНЫЙ. Две первые плитки — это первый экран
 *  главной и её LCP (см. PhotoMasonry); interleave берёт с каждой дорожки
 *  по первой плитке, а у нескольких площадок галерея начинается с широкой
 *  обложки (og-cover) — без этого правила ряд собирался из низких полосок.
 *  Первые n вертикальных плиток выносим вперёд, остальной порядок потока
 *  не трогаем: обложки встают сразу за первым рядом и с него же начинают
 *  рвать ритм колонок. Ровно первый ряд, а не «вход каждой карточки»:
 *  во втором варианте горизонтальные уезжали на второй экран, и первый
 *  снова стоял симметрично. */
function tallLead(pins: Pin[], n: number): Pin[] {
  const lead: Pin[] = [];
  const rest: Pin[] = [];

  for (const p of pins) {
    if (lead.length < n && isPortrait(p.photos[0])) lead.push(p);
    else rest.push(p);
  }

  return [...lead, ...rest];
}

/** по одной штуке с каждой площадки по кругу — доска не идёт блоками
 *  «сначала одна площадка, потом другая» */
function interleave(lanes: Pin[][]): Pin[] {
  const out: Pin[] = [];

  for (let k = 0; lanes.some((lane) => k < lane.length); k++) {
    for (const lane of lanes) {
      if (lane[k]) out.push(lane[k]);
    }
  }

  return out;
}

/** Статья в потоке доски — типографическая плашка: рубрика, заголовок,
 *  «Читать». Без обложки: фото статьи в узкой колонке сливалось с соседними
 *  кадрами, а подпись под ним — с подписью соседней плитки. Плашка той же
 *  пропорции, что кадр каталога, встаёт в ритм доски как текстовый пин. */
export interface ArticleTile {
  kind: 'article';
  href: string;
  rubric: string;
  title: string;
  ratio: string;
  index: number;
  height: number;
}

export type Tile = ({ kind: 'photo' } & Pin) | ArticleTile;

/** через сколько фото-плиток в поток вклинивается статья */
const ARTICLE_EVERY = 5;

// Пропорция плашки статьи = кадр каталога на телефоне (--card-ratio 2:3):
// в колонке из вертикальных кадров она читается как ещё один кадр.
const ARTICLE_RATIO = 2 / 3;

function articleTile(article: (typeof ARTICLES)[number]): ArticleTile {
  return {
    kind: 'article',
    href: articleUrl(article),
    rubric: rubricBySlug(article.rubricSlug)?.title ?? 'Журнал',
    title: article.title,
    ratio: '2 / 3',
    index: 0,
    height: 1 / ARTICLE_RATIO,
  };
}

/** РОВНЫМ ШАГОМ ПО ВСЕЙ ДОСКЕ, А НЕ ХВОСТОМ И НЕ ПАЧКОЙ. Раньше ролики шли
 *  одной дорожкой внутри общего interleave — и расходились только по первым
 *  рядам: дорожек у площадок и подрядчиков столько же, сколько карточек, и
 *  заканчиваются они раньше, чем ролики, поэтому весь хвост видео вставал
 *  в конец доски одной пачкой. Дорожка тут в принципе не годится: она
 *  раскладывает поровну по КРУГАМ, а нужно поровну по ДЛИНЕ.
 *
 *  Поэтому доля, а не дорожка: на каждую плитку base приходится
 *  extra / base плиток extra, накопитель ставит очередную, как только доля
 *  перевалила за единицу. Сколько бы их ни добавили, они лягут ровным
 *  шагом от первой плитки до последней.
 *
 *  Тем же шагом раскладываются и ГОРИЗОНТАЛЬНЫЕ кадры (spreadWide): в
 *  галереях они лежат кучкой (обложка, экстерьер, общий план подряд), и
 *  interleave по карточкам эту кучку не разбивает — на доске низкие плитки
 *  шли одна за другой и ложились столбиком в одну колонку. */
function spread(base: Pin[], extra: Pin[]): Pin[] {
  if (extra.length === 0) return base;
  if (base.length === 0) return extra;

  const out: Pin[] = [];
  const step = extra.length / base.length;
  let due = 0;
  let next = 0;

  for (const pin of base) {
    out.push(pin);
    due += step;

    while (due >= 1 && next < extra.length) {
      out.push(extra[next++]);
      due -= 1;
    }
  }

  // остаток (extra больше, чем base) — досыпается в конец
  out.push(...extra.slice(next));

  return out;
}

/** Горизонтальные — ровным шагом среди вертикальных, первые lead плиток
 *  (первый ряд, tallLead) остаются на месте. */
function spreadWide(pins: Pin[], lead: number): Pin[] {
  const head = pins.slice(0, lead);
  const rest = pins.slice(lead);
  const wide = (p: Pin) => isWide(p.height);
  return [...head, ...spread(rest.filter((p) => !wide(p)), rest.filter(wide))];
}

/** ОДИН КАДР — ОДНА ПЛИТКА. Пять роликов стоят у площадок прямо в
 *  `gallery` (они же кадры первого экрана карточки) и одновременно лежат
 *  в REELS — и лента показывала такой ролик ДВАЖДЫ, в разных местах и
 *  с разным соседством, так что на глаз это читалось не как повтор
 *  кадра, а как сбой. Считаем занятые кадры после сборки фото-дорожек
 *  и выкидываем из роликов те, что уже стоят.
 *
 *  Именно в таком порядке, а не «убрать ролики из gallery»: в галерее
 *  площадки ролик стоит осознанно (первый экран им и листается), и
 *  срезать его там значило бы чинить ленту за счёт карточки. И не
 *  наоборот — приоритет у кадра карточки, потому что он ведёт на саму
 *  площадку, а плитка REELS у ролика без venue/author может вести в никуда. */
function framesOf(pins: Pin[]): Set<string> {
  const used = new Set<string>();
  for (const pin of pins) for (const src of pin.photos) used.add(src);
  return used;
}

/** Доска целиком — один непрерывный поток плиток, без блоков и полос:
 *  колонки просто идут вниз и заканчиваются на разной высоте, как в ленте.
 *  Каждая ARTICLE_EVERY-я позиция — карточка статьи. */
export function collectTiles(): Tile[] {
  // Кадры площадок и подрядчиков идут дорожками в interleave — по одной
  // плитке с карточки по кругу, чтобы доска не шла блоками «сначала одна
  // площадка, потом другая». Горизонтальные разводятся ровным шагом
  // (spreadWide), ролики подмешиваются сверху той же долей (spread).
  const cards = spreadWide(
    tallLead(
      interleave([
        ...VENUES.map((v) => capKeepWide(venuePins(v), PER_CARD_TILES)),
        ...REAL_SPECIALISTS.map((s) => capKeepWide(specialistPins(s), capOf(s))),
      ]),
      2
    ),
    2
  );
  const used = framesOf(cards);
  const photos = spread(
    cards,
    reelPins().filter((pin) => !used.has(pin.photos[0]))
  );
  const articles = ARTICLES.map(articleTile);
  const out: Tile[] = [];

  let a = 0;

  photos.forEach((pin, i) => {
    // статью ставим ПЕРЕД плиткой, чтобы доска не начиналась с неё
    if (i > 0 && i % ARTICLE_EVERY === 0 && articles[a]) out.push(articles[a++]);
    out.push({ kind: 'photo', ...pin });
  });

  // Срез по готовому потоку: площадки/подрядчики/ролики/статьи уже
  // вперемешку, поэтому разнообразие источников не теряется. Порядок
  // детерминирован (данные статичные, никакого Math.random) — HTML
  // одинаковый от сборки к сборке.
  return out.slice(0, BOARD_TILE_LIMIT).map((tile, index) => ({ ...tile, index }));
}

/** Плитки доски из простого списка кадров — галерея карточки подрядчика.
 *  Тут нет ни мини-галерей, ни подписей, ни статей: подпись под каждым
 *  кадром своей же съёмки — шум, а не смысл. Единственное, что берём
 *  от доски главной, — настоящую пропорцию файла и тот же зажим крайних
 *  пропорций (clampRatio): совсем узкая вертикаль в колонке вырастает
 *  на два экрана, панорама — сжимается в щель. Горизонтальный кадр, как
 *  и на доске главной, — просто низкая плитка, колонки он не рвёт.
 */
export function photoTiles(photos: string[], alt: string): Tile[] {
  return photos.map((src, index) => {
    const ratio = clampRatio(src);

    return {
      kind: 'photo',
      owner: null,
      photos: [src],
      alt: `${alt} — фото ${index + 1}`,
      href: null,
      caption: null,
      ratio: `${ratio.toFixed(3)} / 1`,
      index,
      height: 1 / ratio,
    };
  });
}

// ЖАДНАЯ РАСКЛАДКА — тот же алгоритм, что у Masonry.js/MiniMasonry:
// каждая следующая плитка ложится в самую короткую на этот момент колонку.
// Стыки внутри колонки ровные всегда. Не CSS multi-column: тот «балансирует»
// колонки по высоте и заканчивает их с разницей в пару пикселей — читается
// как ошибка, а не как ритм. Колонки одной ширины, поэтому высоты считаются
// в её долях и сходятся с реальными до пикселя. Тем же кодом раскладывает
// клиент (PhotoMasonry), когда колонок на экране больше двух, и он же
// досыпает ленту при прокрутке. Само правило выбора колонки (в том числе
// «низкая под низкой не ложится») — pickColumn в lib/masonry, одно на
// сервер и клиент.
export function layoutColumns(pins: Tile[], count: number): Tile[][] {
  const cols: Tile[][] = Array.from({ length: count }, () => []);
  const tall = new Array<number>(count).fill(0);
  const lastWide = new Array<boolean>(count).fill(false);

  // Статьи идут по колонкам по кругу — первая слева, вторая справа, дальше
  // снова слева: плашка-текст не должна копиться на одной вертикали, но и
  // выбирать ей колонку жадно нельзя — тогда все статьи сваливаются в одну.
  let article = 0;

  for (const p of pins) {
    let k = article % count;

    if (p.kind === 'article') {
      article++;
    } else {
      k = pickColumn(tall, lastWide, isWide(p.height));
    }

    cols[k].push(p);
    tall[k] += p.height;
    lastWide[k] = isWide(p.height);
  }

  return cols;
}
