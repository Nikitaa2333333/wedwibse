// ============================================================
// РЕЕСТР ИЗОБРАЖЕНИЙ — единая точка входа в оптимизацию Astro.
// Данные (feed.ts, specialists.ts, venues.ts) хранят фото как обычные
// строки-пути ('/venues/river-loft/gal/g4.webp') — так их удобно листать,
// сравнивать, отдавать в JSON фильтров. Здесь строка превращается в
// ImageMetadata, которую понимает <Image> из astro:assets: тот сам
// пережимает файл, режет под нужные ширины и отдаёт srcset.
//
// import.meta.glob подхватывает исходники ТОЛЬКО из src/ — поэтому все
// фотографии карточек должны лежать в src/assets/..., а не в
// public/ (публичная папка отдаётся как есть, без сжатия). Новая категория
// (площадки, подрядчики) — просто кладём файлы в свою подпапку src/assets/,
// глобу для этого ничего менять не нужно.
// ============================================================
import type { ImageMetadata } from 'astro';
import { getImage } from 'astro:assets';

const modules = import.meta.glob<{ default: ImageMetadata }>(
  '/src/assets/**/*.{webp,jpg,jpeg,png}',
  { eager: true }
);

const registry = new Map<string, ImageMetadata>(
  Object.entries(modules).map(([path, mod]) => [path.replace(/^\/src\/assets/, ''), mod.default])
);

// ============================================================
// ШИРИНЫ srcset ПО РОЛИ КАДРА — единый набор на весь проект.
//
// Ширины подбираются не «на глаз под этот блок», а по роли: сколько места
// кадр занимает на экране. Раньше каждая страница писала свой массив, и
// наборы тихо разъезжались — у карточки площадки потолок был 1800, у такой
// же карточки специалиста 1200, и кадр во всю ширину телефона при DPR 2
// растягивался из 1200 в ~1700 реальных пикселей и мылил.
//
// ПОТОЛОК НЕ ДЕЛАЕТ СТРАНИЦУ ТЯЖЕЛЕЕ. Браузер выбирает ОДНУ ширину из
// srcset по sizes и своему DPR: телефон с узкой колонкой возьмёт 360 и при
// потолке 1800, и при потолке 800. Лишняя большая ширина стоит только
// места на диске сборки — зато без неё крупный экран получает растянутый
// кадр, и это видно сразу. Поэтому потолок ставим ПОД САМЫЙ БОЛЬШОЙ
// возможный показ кадра, а вес держим честным sizes, а не занижением
// потолка.
//
// ВТОРАЯ ПОЛОВИНА ПРАВИЛА — В ИСХОДНИКЕ (см. CLAUDE.md, раздел изображений):
// srcset не может выдать больше, чем лежит в src/assets, и не спасёт кадр,
// который уже пережали до укладки в репозиторий.
// ============================================================
export const IMG_WIDTHS = {
  /** кадр во всю ширину экрана: первый экран карточки, сплит-герой.
   *  Шаг 1400 добавлен не для красоты: телефону 430 px при DPR 3 нужно
   *  1290, а из набора без него браузер брал сразу 1800 — почти мегабайт
   *  на первом экране. Потолок при этом не тронут (см. CLAUDE.md: занижать
   *  его нельзя), просто лестница стала без провала посередине. */
  hero: [480, 800, 1200, 1400, 1800],
  /** широкий кадр внутри контента: обложка статьи, перк доски, wide-ячейка */
  wide: [560, 900, 1400, 1800],
  /** карточка каталога в сетке 2–4 колонки */
  card: [360, 560, 800, 1100],
  /** плитка доски-масонри: колонка узкая, выше 800 там не нужно */
  tile: [360, 560, 800],
  /** полноэкранная сцена скролли-блока — единственное место, где нужен 2400 */
  stage: [720, 1200, 1800, 2400],
  /** мелкий кадр: метка карты, логотип, кружок автора */
  thumb: [220, 440],
  /** размытая подложка первого экрана (HeroStage): кадр под blur 36px —
   *  разрешение ему не нужно вовсе, а появиться он должен раньше самого
   *  кадра, иначе на экране висит пустая заливка */
  blur: [320, 640],
} as const;

/** path — тот же строковый путь, что лежит в данных, например '/venues/river-loft/gal/g4.webp' */
export function resolveImage(path: string): ImageMetadata {
  const image = registry.get(path);
  if (!image) {
    throw new Error(`resolveImage: нет файла в src/assets для пути "${path}" — проверь, что фото лежит в src/assets, а не только в public`);
  }
  return image;
}

/**
 * Готовый URL пережатого кадра для снимка в localStorage (избранное):
 * туда нельзя класть путь из данных — файл живёт только в src/assets и по
 * такому адресу не отдаётся. Ширина 800 — хватает на обложку папки и карточку.
 */
export async function favoriteImage(path: string): Promise<string> {
  const img = await getImage({ src: resolveImage(path), width: 800, format: 'webp' });
  return img.src;
}
