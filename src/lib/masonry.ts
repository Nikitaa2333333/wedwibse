/** низкая плитка — кадр шире, чем выше; именно она сдвигает колонку на
 *  полкадра и делает ритм доски рваным (см. шапку lib/gallery). Высота —
 *  в долях ширины колонки, та же, что в data-h у плитки. */
export function isWide(height: number): boolean {
  return height < 1;
}

/** ЖАДНО, НО НИЗКАЯ ПОД НИЗКОЙ НЕ ЛОЖИТСЯ. У чистого жадного алгоритма
 *  («в самую короткую колонку») есть слепое пятно: после горизонтальной
 *  плитки колонка остаётся самой короткой, и следующая горизонтальная
 *  ложится в неё же — на доске получался столбик низких полосок в одной
 *  колонке, а соседняя стояла одним вертикальным кадром. Так горизонтальные
 *  не сдвигают колонки друг относительно друга, а наоборот, выравнивают их.
 *  Поэтому низкой плитке берём самую короткую колонку из тех, что НЕ
 *  заканчиваются низкой; заканчиваются все — обычная жадная. */
export function pickColumn(tall: number[], lastWide: boolean[], wide: boolean): number {
  let k = -1;

  for (let j = 0; j < tall.length; j++) {
    if (wide && lastWide[j]) continue;
    if (k < 0 || tall[j] < tall[k]) k = j;
  }

  if (k >= 0) return k;

  k = 0;
  for (let j = 1; j < tall.length; j++) if (tall[j] < tall[k]) k = j;
  return k;
}
