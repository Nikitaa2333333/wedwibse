// БИРКА ПОД ИМЕНЕМ ПОДРЯДЧИКА: «Профессия · строка под именем».
// Профессия встаёт сама (из раздела), строку пишет подрядчик в кабинете.
// Если в строке профессия уже названа («Ведущий, а не тамада…»,
// «Кейтеринг от 30 до 3000 гостей», «Свадебный стилист и визажист»),
// второй раз её не ставим — иначе «Ведущий · Ведущий, а не тамада»
// (заказчик, 09.11.2026). Модуль без зависимостей: его же зовёт
// предпросмотр в кабинете (kartochka.astro), вид должен совпадать с сайтом.

/** основа слова без окончания: «ведущий» → «ведущ», «кавер-группа» → «кавер-групп» */
const base = (w: string) => w.replace(/(ий|ый|ая|ые|ие|[аяыиоуе])$/, '');

/** формы слова профессии, которые считаем упоминанием: падежи и число
 *  («фотографов», «кавер-групп»), прилагательное («ведущая», «кондитерская»).
 *  «Фотографии» — уже не профессия: окончания «ии» в списке нет. */
const ENDINGS = ['', 'а', 'я', 'у', 'ю', 'ом', 'ем', 'е', 'ы', 'и', 'ов', 'ев', 'ам', 'ами', 'ах',
  'ий', 'ая', 'ие', 'его', 'ей', 'их', 'ую', 'ее', 'ой', 'ский', 'ская', 'ской', 'скую', 'ские', 'ских'];

const words = (s: string) => {
  const ws = s.toLowerCase().replace(/ё/g, 'е').split(/[^a-zа-я-]+/).filter(Boolean);
  // «шоу-персонажи»: проверяем и слово целиком, и его части через дефис
  return [...new Set(ws.flatMap((w) => [w, ...w.split('-')]))].filter((w) => w.length >= 3);
};

/** названа ли профессия в строке. names — все формы профессии
 *  (единственное, множественное, женский род). */
export function mentionsRole(tagline: string, names: string[]): boolean {
  const bases = [...new Set(names.flatMap(words).map(base))].filter((b) => b.length >= 2);
  return words(tagline).some((w) => bases.some((b) => w.startsWith(b) && ENDINGS.includes(w.slice(b.length))));
}

export function joinKicker(role: string, tagline: string | undefined, names: string[] = [role]): string {
  const t = (tagline ?? '').trim();
  if (!t) return role;
  if (!role || mentionsRole(t, names)) return t;
  return `${role} · ${t}`;
}
