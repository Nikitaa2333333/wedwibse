// СКЛЕЙКА ЧИСЕЛ И ЦЕН (заказчик, 09.11.2026: «рубли отвалились»).
// Цена в строке не рвётся: «12 000 ₽» целиком, «— 7 000 ₽» не начинает
// новую строку с тире, «от 40 000 ₽» не оставляет «от» висеть в конце.
// Текст из данных и из кабинета приходит с обычными пробелами — склеиваем
// на выводе, а не правкой каждого JSON. Закон — CLAUDE.md, «Цены».
const NB = ' ';

export function glue(text: string): string;
export function glue(text: string | undefined | null): string | undefined;
export function glue(text: string | undefined | null): string | undefined {
  if (!text) return text ?? undefined;
  return (
    text
      // разряды: «12 000», «1 200 000» (обычный, узкий или неразрывный пробел)
      .replace(/(\d)[   ](?=\d{3}(?!\d))/g, `$1${NB}`)
      // число и единица: «7 000 ₽», «50 %», «120 м²», «30 гостей» не трогаем
      .replace(/(\d)[  ](?=(?:₽|руб|%|м²|км\b|тыс\b|млн\b))/g, `$1${NB}`)
      // предлог перед числом: «от 40 000», «до 30»
      .replace(/(^|[\s(«])(от|до|за|по|с|на|ок\.)[ ](?=\d)/gi, `$1$2${NB}`)
      // тире не начинает строку: «Образ в студии — 7 000 ₽»
      .replace(/ (—|–)(?=\s)/g, `${NB}$1`)
  );
}
