// ============================================================
// «УЖЕ СМОТРЕЛ» — какие карточки человек открывал.
//
// Нужно карте (реф. ЦИАН): метка открытой площадки гаснет, и на карте
// с десятками точек сразу видно, что осталось. Без этого человек ходит
// по кругу — метки все одинаковые, а вспомнить, на какую он уже нажимал,
// после третьей невозможно.
//
// До появления личного кабинета живёт в localStorage этого браузера,
// ровно как «Избранное» (lib/favorites). Появится кабинет — список
// переезжает в него, а вызовы markSeen/isSeen остаются теми же.
//
// Храним ТОЛЬКО слаги, без дат и снимков: это подсказка на карте, а не
// история просмотров. Полноценная история — задача личного кабинета,
// и собирать её молча в браузере до того, как о ней сказано человеку,
// мы не будем.
// ============================================================

const KEY = 'wed:seen';
/** больше не храним: список подсказка, а не архив */
const LIMIT = 500;

function read(): string[] {
  try {
    const raw = localStorage.getItem(KEY);
    return raw ? (JSON.parse(raw) as string[]) : [];
  } catch {
    // приватная вкладка или запрет на хранилище — карта просто не гасит метки
    return [];
  }
}

/** `venue:forest-dew` — каталог в ключе, чтобы слаги разных каталогов не сошлись */
export function seenId(cat: string, slug: string): string {
  return `${cat}:${slug}`;
}

export function isSeen(id: string): boolean {
  return read().includes(id);
}

/** все отметки разом — карте нужен весь список, а не по одному ключу */
export function seenSet(): Set<string> {
  return new Set(read());
}

export function markSeen(id: string): void {
  const list = read();
  if (list.includes(id)) return;

  list.push(id);
  try {
    localStorage.setItem(KEY, JSON.stringify(list.slice(-LIMIT)));
  } catch {
    // хранилище недоступно или переполнено — отметка просто не сохранится
  }
}
